GREEN, AMBER, RED, GREY = "green", "#f59e0b", "red", "#6b7280"


def is_ok(s):
    return f"({s['expr']}) < {s['red']}" if s["dir"] == "low" else f"({s['expr']}) >= {s['red']}"


def is_bad(s):
    return f"({s['expr']}) >= {s['red']}" if s["dir"] == "low" else f"({s['expr']}) < {s['red']}"


