def render_block():
    out = [DASH_BEGIN]
    for set_key, (_, dashes) in SETS.items():
        out.append(f"          {set_key}:")
        for key, fn in dashes.items():
            out.append(f"            {key}:")
            out.append("              json: |")
            for line in json.dumps(fn(), indent=2).split("\n"):
                out.append("                " + line)
    out.append(DASH_END)
    return "\n".join(out)


def render_provider():
    out = [PROV_BEGIN]
    for set_key, (folder, _) in SETS.items():
        out += [f"              - name: {set_key}", "                orgId: 1", f"                folder: '{folder}'",
                "                type: file", "                disableDeletion: false", "                editable: false",
                "                options:", f"                  path: /var/lib/grafana/dashboards/{set_key}"]
    out.append(PROV_END)
    return "\n".join(out)


def splice(src, begin, end, block, anchor):
    if begin in src:
        a, b = src.index(begin), src.index(end) + len(end)
        return src[:a] + block + src[b:]
    if anchor not in src:
        sys.exit(f"anchor not found: {anchor!r}")
    return src.replace(anchor, block + "\n" + anchor, 1)


def main():
    src = TARGET.read_text()
    new = splice(src, PROV_BEGIN, PROV_END, render_provider(),
                 "        dashboards:\n          golden-signals:")
    # providers block sits right before `dashboards:`; keep the list contiguous
    new = splice(new, DASH_BEGIN, DASH_END, render_block(), "  destination:\n    server:")
    if "--check" in sys.argv:
        if new != src:
            sys.exit("grafana.yaml is stale: run scripts/gen-slo-dashboards.py")
        return
    TARGET.write_text(new)


if __name__ == "__main__":
    main()
